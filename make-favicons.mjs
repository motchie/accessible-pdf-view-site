#!/usr/bin/env node
/**
 * Rasterises `public/favicon.svg` into the files browsers actually request.
 *
 * `favicon.svg` is the source of truth — the same mark geometry as the
 * `.lock__mark` inline in every page, with `currentColor` fixed to `#1a73e8`
 * because a standalone favicon file has no page to inherit a colour from.
 * Modern browsers use the SVG directly; these outputs exist for the ones that
 * do not, and for the plain `/favicon.ico` request browsers still make
 * regardless of what `<link rel="icon">` says.
 *
 * Rendered with Playwright (already a devDependency, for `a11y-check.mjs`)
 * rather than a hand-rolled rasteriser: real Chromium is the only thing in
 * this toolchain that already draws SVG correctly, and this mark is two
 * strokes, not worth a second renderer.
 *
 * `favicon.ico` is hand-assembled rather than generated by a library: since
 * Windows Vista the ICO container accepts a plain PNG payload per entry, so
 * "encode a real ICO" is fifteen bytes of header around PNGs this script
 * already made — see `buildIco` below.
 */
import { chromium } from 'playwright';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const svgPath = join(root, 'public/favicon.svg');

/** 16 and 32 go into favicon.ico; 180 is the iOS home-screen icon. */
const ICO_SIZES = [16, 32];
const APPLE_TOUCH_SIZE = 180;

async function renderPng(page, size) {
  await page.setViewportSize({ width: size, height: size });
  return page.screenshot({ omitBackground: true });
}

async function main() {
  const svg = await readFile(svgPath, 'utf8');
  const dataUrl = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;

  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 32, height: 32 } });
  // A page whose only content is the SVG at exactly 100% of the viewport, so
  // the screenshot needs no cropping and no browser chrome shows through.
  await page.setContent(
    `<style>html,body{margin:0;padding:0}img{display:block;width:100%;height:100%}</style>` +
      `<img src="${dataUrl}" alt="" />`,
  );

  const icoPngs = [];
  for (const size of ICO_SIZES) {
    const png = await renderPng(page, size);
    icoPngs.push({ size, png });
  }
  const applePng = await renderPng(page, APPLE_TOUCH_SIZE);

  await browser.close();

  await mkdir(join(root, 'public'), { recursive: true });
  await writeFile(join(root, 'public/favicon.ico'), buildIco(icoPngs));
  await writeFile(join(root, 'public/apple-touch-icon.png'), applePng);

  console.log(`wrote public/favicon.ico (${ICO_SIZES.join('+')}px) and public/apple-touch-icon.png (${APPLE_TOUCH_SIZE}px)`);
}

/**
 * ICONDIR + one ICONDIRENTRY per image + the raw PNG bytes, back to back.
 * Byte layout is the documented Microsoft ICO format (MS-ICO); the only
 * modern wrinkle is that an entry's payload may be a PNG file verbatim
 * instead of a BMP, which every current browser and OS accepts.
 */
function buildIco(images) {
  const HEADER_SIZE = 6;
  const ENTRY_SIZE = 16;
  const headerAndDir = Buffer.alloc(HEADER_SIZE + ENTRY_SIZE * images.length);

  headerAndDir.writeUInt16LE(0, 0); // reserved
  headerAndDir.writeUInt16LE(1, 2); // type: 1 = icon
  headerAndDir.writeUInt16LE(images.length, 4);

  let offset = headerAndDir.length;
  const chunks = [headerAndDir];
  images.forEach(({ size, png }, index) => {
    const entry = headerAndDir.subarray(HEADER_SIZE + index * ENTRY_SIZE, HEADER_SIZE + (index + 1) * ENTRY_SIZE);
    entry.writeUInt8(size >= 256 ? 0 : size, 0); // width, 0 means 256
    entry.writeUInt8(size >= 256 ? 0 : size, 1); // height, 0 means 256
    entry.writeUInt8(0, 2); // palette colours: none
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(png.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += png.length;
    chunks.push(png);
  });

  return Buffer.concat(chunks);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
